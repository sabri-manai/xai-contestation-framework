"""Understand as a closed choice (12 Nov 2026, v2).

The adapter enumerates what a turn can be about (claim_menu). Step 1 picks one entry: Jev (choice question
with probabilities) in the decision track, a language model in the language track. Step 2 fills only the
slots that entry defines (a language model in both tracks: Jev does not extract values). Kind, subject and
feature follow from the entry by construction. A low choice probability is itself a reason to ask
(Surface-clarify): the reject option applied to Understand.

v1 (free-form JSON with the kind and subject generated by the model) is kept in common.understand_llm for
comparison; its failures were slot mismatches and invented fact keys (e5_live.md, first run).
"""
from __future__ import annotations

import json
import re

from ..api import chat, jev_decide, parse_json
from ..schemas import Grounds

SLOT_MODEL = "openai/gpt-4o-mini"
CLARIFY_TAU = 0.5   # rule: below this choice probability the system asks which claim the user means

DOMAIN_TASK = {
    "cfxhpo": "An operator replies to a configuration recommendation (a table of options with predicted quality and constraint status, and a generated explanation). Which of the listed claims is the operator's TURN about?",
    "fungi": "A study participant comments on an explanation of an AI mushroom classifier (described by its caption and the facts it shows). Which of the listed claims is the participant's TURN about?",
}


def _key(entry_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", entry_id)


def choose_jev(domain: str, user_text: str, state: dict, menu: list[dict], repeat: int = 0) -> tuple[str, float, dict]:
    keys = {_key(e["id"]): e["id"] for e in menu}
    questions = {"claim": {"type": "choice", "instructions": DOMAIN_TASK[domain] + " Pick the single best match; 'none' if nothing applies.",
                           "criteria": {_key(e["id"]): e["text"] for e in menu}}}
    st = {"task": DOMAIN_TASK[domain], "explanation": state, "user_turn": user_text}
    res = jev_decide(st, questions, repeat=repeat, cache_kind="jev_understand")
    a = res["answers"]["claim"]
    probs = {keys.get(k, k): float(v) for k, v in a.get("probabilities", {}).items()}
    chosen = keys.get(a["choice"], a["choice"])
    return chosen, probs.get(chosen, float(a.get("confidence", 0))), probs


def choose_llm(domain: str, user_text: str, state: dict, menu: list[dict], model: str = SLOT_MODEL, repeat: int = 0) -> tuple[str, float, dict]:
    sys_ = (DOMAIN_TASK[domain] + ' Answer with one JSON object: {"id": "<id of the single best matching claim>", "confidence": <0-1>}. Use "none" if nothing applies.')
    user = json.dumps({"explanation": state, "user_turn": user_text, "claims": [{"id": e["id"], "text": e["text"]} for e in menu]}, ensure_ascii=False)
    out = chat(model, [{"role": "system", "content": sys_}, {"role": "user", "content": user}], max_tokens=80, json_mode=True, repeat=repeat, cache_kind="llm_understand")
    try:
        j = parse_json(out["text"])
        cid = str(j.get("id", "none")); conf = float(j.get("confidence", 0.5))
    except Exception:
        cid, conf = "none", 0.0
    ids = {e["id"] for e in menu}
    if cid not in ids:
        cid = next((e["id"] for e in menu if e["id"].lower() == cid.lower()), "none"); conf = min(conf, 0.5)
    return cid, conf, {cid: conf}


def fill_slots(user_text: str, entry: dict, repeat: int = 0) -> dict:
    if not entry.get("slots"):
        return {}
    sys_ = ("Extract values from the user's turn for the slots listed. Output one JSON object with exactly those keys; "
            "use null for a slot the turn does not state.")
    user = json.dumps({"user_turn": user_text, "claim": entry["text"], "slots": entry["slots"]}, ensure_ascii=False)
    out = chat(SLOT_MODEL, [{"role": "system", "content": sys_}, {"role": "user", "content": user}], max_tokens=120, json_mode=True, repeat=repeat, cache_kind="llm_slots")
    try:
        j = parse_json(out["text"])
        return {k: v for k, v in j.items() if v is not None}
    except Exception:
        return {}


# default taxonomy labels per claim kind (what Understand v1 generated; here they follow from the chosen claim)
KIND_LABELS = {
    "score_reach": ("prediction", "direct challenge", "prior experience"),
    "score_over": ("prediction", "direct challenge", "technical knowledge"),
    "rank_confirmed": ("reasoning", "alternative proposal", "prior experience"),
    "rank_table": ("explanation representation", "direct challenge", "presentation ambiguity"),
    "satisfies": ("explanation representation", "direct challenge", "internal inconsistency"),
    "feature_effect": ("reasoning", "direct challenge", "causal implausibility"),
    "density": ("evidence", "direct challenge", "missing evidence"),
    "log_stat": ("input data", "direct challenge", "data-quality concern"),
    "units": ("explanation representation", "direct challenge", "presentation ambiguity"),
    "fact": ("explanation representation", "direct challenge", "presentation ambiguity"),
    "model_effect": ("reasoning", "direct challenge", "causal implausibility"),
    "uncheckable": ("reasoning", "rejection", "domain knowledge"),
    "request": ("", "", ""), "none": ("", "", ""),
}


def understand(adapter, domain: str, user_text: str, track: str = "decision", repeat: int = 0) -> Grounds:
    menu = adapter.claim_menu()
    state = adapter.state()
    if track == "decision":
        cid, conf, probs = choose_jev(domain, user_text, state, menu, repeat=repeat)
    else:
        cid, conf, probs = choose_llm(domain, user_text, state, menu, repeat=repeat)
    entry = next((e for e in menu if e["id"] == cid), menu[-1])
    uv = dict(entry["user_value"]) if isinstance(entry["user_value"], dict) else entry["user_value"]
    slots = fill_slots(user_text, entry, repeat=repeat)
    if slots:
        uv = dict(uv or {}, **slots) if isinstance(uv, dict) or uv is None else slots
    t, a, gr = KIND_LABELS.get(entry["kind"], ("", "", ""))
    return Grounds(target=t, act=a, grounds=gr, claim_kind=entry["kind"], subject=entry["subject"], user_value=uv,
                   extra={"menu_id": cid, "choice_confidence": conf, "clarify": conf < CLARIFY_TAU, "user_text": user_text, "n_menu": len(menu)})
